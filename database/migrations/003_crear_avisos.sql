CREATE TABLE avisos (
  id                INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  titulo            VARCHAR(140) NOT NULL,
  slug              VARCHAR(160) NOT NULL COMMENT 'La URL se resuelve por id; si el slug no coincide se hace 301',
  tipo              ENUM('mensual','temporario') NOT NULL,
  categoria         ENUM('casa','departamento','monoambiente','ph','local','habitacion') NOT NULL,
  ambientes         TINYINT UNSIGNED NULL,
  dormitorios       TINYINT UNSIGNED NULL,
  banos             TINYINT UNSIGNED NULL,
  barrio_id         SMALLINT UNSIGNED NULL COMMENT 'NULL solo mientras está pendiente con barrio_sugerido',
  barrio_sugerido   VARCHAR(80) NULL COMMENT 'Texto libre de /publicar cuando eligen "No sé / otro"',
  direccion         VARCHAR(160) NULL,
  mostrar_direccion TINYINT(1) NOT NULL DEFAULT 0,
  lat               DECIMAL(9,6) NULL,
  lng               DECIMAL(9,6) NULL,
  precio            INT UNSIGNED NULL COMMENT 'NULL = Consultar. Sin centavos',
  moneda            ENUM('ARS','USD') NOT NULL DEFAULT 'ARS',
  periodo           ENUM('mes','dia') NOT NULL,
  expensas          INT UNSIGNED NULL COMMENT 'Siempre ARS. NULL = no informa, 0 = sin expensas',
  descripcion       TEXT NOT NULL,
  contacto_whatsapp VARCHAR(20)  NULL,
  contacto_telefono VARCHAR(30)  NULL,
  contacto_email    VARCHAR(160) NULL,
  publicador        ENUM('particular','inmobiliaria') NOT NULL DEFAULT 'particular',
  inmobiliaria_id   SMALLINT UNSIGNED NULL,
  destacado         TINYINT(1) NOT NULL DEFAULT 0,
  estado            ENUM('pendiente','activo','pausado','alquilado','rechazado') NOT NULL DEFAULT 'pendiente',
  motivo_estado     VARCHAR(255) NULL,
  origen            ENUM('admin','formulario') NOT NULL,
  fuente_url        VARCHAR(500) NULL COMMENT 'Interno: de dónde se relevó el aviso',
  token_gestion     CHAR(64) NULL COMMENT 'SHA-256 del token del link de verificación',
  ultima_verificacion        DATETIME NULL,
  verificacion_solicitada_en DATETIME NULL,
  publicado_en      DATETIME NULL COMMENT 'Primera vez que pasó a activo',
  ip_origen         VARBINARY(16) NULL,
  creado_en         DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  actualizado_en    DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT fk_avisos_barrio FOREIGN KEY (barrio_id) REFERENCES barrios (id),
  CONSTRAINT fk_avisos_inmobiliaria FOREIGN KEY (inmobiliaria_id) REFERENCES inmobiliarias (id),
  CONSTRAINT chk_avisos_publicador CHECK (
    (publicador = 'particular'   AND inmobiliaria_id IS NULL) OR
    (publicador = 'inmobiliaria' AND inmobiliaria_id IS NOT NULL)),
  CONSTRAINT chk_avisos_contacto CHECK (
    contacto_whatsapp IS NOT NULL OR contacto_telefono IS NOT NULL OR contacto_email IS NOT NULL),
  CONSTRAINT chk_avisos_barrio CHECK (
    barrio_id IS NOT NULL OR (estado IN ('pendiente','rechazado') AND barrio_sugerido IS NOT NULL)),
  CONSTRAINT chk_avisos_coordenadas CHECK ((lat IS NULL) = (lng IS NULL)),
  KEY idx_avisos_listado  (estado, tipo, categoria, barrio_id, destacado, publicado_en),
  KEY idx_avisos_barrio   (estado, barrio_id, publicado_en),
  KEY idx_avisos_inmo     (estado, inmobiliaria_id),
  KEY idx_avisos_frescura (estado, ultima_verificacion)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
